type Frame = "informative" | "narrative";

function reading(
  passages: [string, string, string, string, string, string],
  questions: [string, string, string, string, string, string],
  answers: [string, string, string, string, string, string],
): Sextuple {
  return [
    { passage: passages[0], question: questions[0], answer: answers[0] },
    { passage: passages[1], question: questions[1], answer: answers[1] },
    { passage: passages[2], question: questions[2], answer: answers[2] },
    { passage: passages[3], question: questions[3], answer: answers[3] },
    { passage: passages[4], question: questions[4], answer: answers[4] },
    { passage: passages[5], question: questions[5], answer: answers[5] },
  ];
}

function writing(
  prompts: [string, string, string, string, string, string],
  frames: [Frame, Frame, Frame, Frame, Frame, Frame],
  parts: [string[], string[], string[], string[], string[], string[]],
): Sextuple {
  return [
    { frame: frames[0], prompt: prompts[0], requiredParts: parts[0] },
    { frame: frames[1], prompt: prompts[1], requiredParts: parts[1] },
    { frame: frames[2], prompt: prompts[2], requiredParts: parts[2] },
    { frame: frames[3], prompt: prompts[3], requiredParts: parts[3] },
    { frame: frames[4], prompt: prompts[4], requiredParts: parts[4] },
    { frame: frames[5], prompt: prompts[5], requiredParts: parts[5] },
  ];
}

function language(
  sentences: [string, string, string, string, string, string],
  fixed: [string, string, string, string, string, string],
): Sextuple {
  return [
    { sentence: sentences[0], fixed: fixed[0] },
    { sentence: sentences[1], fixed: fixed[1] },
    { sentence: sentences[2], fixed: fixed[2] },
    { sentence: sentences[3], fixed: fixed[3] },
    { sentence: sentences[4], fixed: fixed[4] },
    { sentence: sentences[5], fixed: fixed[5] },
  ];
}

